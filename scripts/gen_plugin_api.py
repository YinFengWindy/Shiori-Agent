"""Write the plugin API reference from the kernel and core socket contracts.

python -m scripts.gen_plugin_api
python -m scripts.gen_plugin_api --check
"""

from __future__ import annotations

import argparse
import dataclasses
import importlib
import inspect
import sys
from pathlib import Path
from typing import Any, get_args, get_type_hints

from shiori_sdk import __version__
from shiori_sdk.kernel import Key
from shiori_sdk.kernel.diagnostics import PluginDiagnostic
from shiori_sdk.runtime import HostServiceUnavailable, PluginRuntimeContext

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "_handbook" / "plugin-api.md"

_CORE_MODULES = (
    "shiori_sdk.core.conversation",
    "shiori_sdk.core.crash_reporting",
    "shiori_sdk.core.memory",
    "shiori_sdk.core.models",
    "shiori_sdk.core.services",
    "shiori_sdk.core.sessions",
    "shiori_sdk.core.tools",
)
# ``setup(ctx)`` receives ``PluginRuntimeContext``; the kernel's own
# ``Context`` (with ``spawn`` / ``on_drain``) is host-side and not rendered.
_KERNEL_TYPES = (
    PluginRuntimeContext,
    HostServiceUnavailable,
    Key,
    PluginDiagnostic,
)


def render() -> str:
    """Return the reference markdown, including a trailing newline."""
    lines = [
        "# Plugin API reference",
        "",
        f"Generated by `scripts/gen_plugin_api.py` from SDK {__version__}. Do not edit.",
        "",
        "Signatures, and each docstring collapsed to one paragraph.",
        "Within this major, existing keys do not gain methods;",
        "a new capability is a new key or a new event.",
        "",
        "## Kernel",
        "",
    ]
    seen: set[type] = set()
    for cls in _KERNEL_TYPES:
        _render_type(cls, lines, seen)
    from shiori_sdk.kernel.contracts import (
        PluginFailed,
        PluginStarted,
        PluginStopped,
        Veto,
    )

    for cls in (Veto, PluginStarted, PluginFailed, PluginStopped):
        _render_type(cls, lines, seen)
    for module_name in _CORE_MODULES:
        module = importlib.import_module(module_name)
        lines.append(f"## `{module_name}`")
        lines.append("")
        doc = inspect.getdoc(module)
        if doc:
            lines.append(_paragraph(doc))
            lines.append("")
        rendered: list[type] = []
        for key_name, _attr, _value, target, label in _keys(module):
            lines.append(f"### `{key_name}`")
            lines.append("")
            if isinstance(target, type) and _from_sdk(target):
                lines.append(f"Target `{target.__module__}.{target.__qualname__}`.")
                lines.append("")
                _render_type(target, lines, seen)
                rendered.append(target)
            elif label:
                lines.append(f"Target `{label}`.")
                lines.append("")
        for cls in _local_types(module):
            if cls in rendered or cls in seen:
                continue
            if not _interesting(cls):
                continue
            _render_type(cls, lines, seen)
    text = "\n".join(lines).rstrip() + "\n"
    return text


def _keys(module: Any) -> list[tuple[str, str, Key[Any], Any, str]]:
    hints = get_type_hints(module)
    found: list[tuple[str, str, Key[Any], Any, str]] = []
    for name, value in vars(module).items():
        if not isinstance(value, Key):
            continue
        hint = hints.get(name)
        args = get_args(hint) if hint is not None else ()
        target = args[0] if len(args) == 1 else None
        own = isinstance(target, type) and _from_sdk(target)
        label = "" if own else _fmt(target or hint)
        found.append((value.name, name, value, target, label))
    found.sort(key=lambda item: (item[0], item[1]))
    return found


def _local_types(module: Any) -> list[type]:
    classes = [
        value
        for name, value in vars(module).items()
        if not name.startswith("_")
        and inspect.isclass(value)
        and value.__module__ == module.__name__
    ]
    classes.sort(key=lambda cls: cls.__qualname__)
    return classes


def _from_sdk(cls: type) -> bool:
    """Only SDK types are expanded: a builtin's members change with the interpreter."""
    return cls.__module__.split(".")[0] == "shiori_sdk"


def _interesting(cls: type) -> bool:
    if dataclasses.is_dataclass(cls):
        return True
    if issubclass(cls, Exception):
        return True
    return bool(getattr(cls, "_is_protocol", False))


def _render_type(cls: type, lines: list[str], seen: set[type]) -> None:
    if cls in seen:
        lines.append(f"#### `{cls.__module__}.{cls.__qualname__}`")
        lines.append("")
        lines.append("Documented above.")
        lines.append("")
        return
    seen.add(cls)
    lines.append(f"#### `{cls.__module__}.{cls.__qualname__}`")
    lines.append("")
    doc = inspect.getdoc(cls)
    if doc:
        lines.append(_paragraph(doc))
        lines.append("")
    if dataclasses.is_dataclass(cls):
        hints = _hints(cls)
        for item in dataclasses.fields(cls):
            lines.append(f"- `{item.name}: {_fmt(hints.get(item.name, item.type))}`")
        if dataclasses.fields(cls):
            lines.append("")
    methods = _methods(cls)
    for name, func, kind in methods:
        if kind == "property":
            returned = _fmt(
                _hints(func).get("return", inspect.signature(func).return_annotation)
            )
            rendered = f"{name}: {returned}" if returned else name
            lines.append(f"- `{rendered}`")
        else:
            prefix = "async " if inspect.iscoroutinefunction(func) else ""
            lines.append(f"- `{prefix}{name}{_signature(func)}`")
        method_doc = inspect.getdoc(func)
        if method_doc:
            lines.append("")
            lines.append(f"  {_paragraph(method_doc)}")
            lines.append("")
    if methods and not inspect.getdoc(methods[-1][1]):
        lines.append("")


def _methods(cls: type) -> list[tuple[str, Any, str]]:
    found: list[tuple[str, Any, str]] = []
    for name, member in cls.__dict__.items():
        if name.startswith("_"):
            continue
        kind = "method"
        func = member
        if isinstance(member, property):
            func = member.fget
            kind = "property"
        elif isinstance(member, (classmethod, staticmethod)):
            func = member.__func__
        if callable(func):
            found.append((name, func, kind))
    return found


def _signature(func: Any) -> str:
    signature = inspect.signature(func)
    hints = _hints(func)
    chunks: list[str] = []
    saw_keyword = False
    for name, param in signature.parameters.items():
        if name == "self":
            continue
        if param.kind is inspect.Parameter.KEYWORD_ONLY and not saw_keyword:
            chunks.append("*")
            saw_keyword = True
        piece = name
        if param.kind is inspect.Parameter.VAR_POSITIONAL:
            # ``*args`` already ends the positional parameters; no bare ``*``.
            piece, saw_keyword = f"*{name}", True
        elif param.kind is inspect.Parameter.VAR_KEYWORD:
            piece = f"**{name}"
        rendered = _fmt(hints.get(name, param.annotation))
        if rendered:
            piece = f"{piece}: {rendered}"
        if param.default is not inspect.Signature.empty:
            piece = f"{piece} = {param.default!r}"
        chunks.append(piece)
    returned = _fmt(hints.get("return", signature.return_annotation))
    suffix = f" -> {returned}" if returned else ""
    return f"({', '.join(chunks)}){suffix}"


def _hints(obj: Any) -> dict[str, Any]:
    """Resolved annotations; an unresolvable forward reference fails the run."""
    return get_type_hints(obj)


def _fmt(annotation: object) -> str:
    if annotation is inspect.Signature.empty or annotation is None:
        return "" if annotation is inspect.Signature.empty else "None"
    if isinstance(annotation, str):
        text = annotation
    else:
        text = inspect.formatannotation(annotation)
    # ``asyncio.Task`` reports the C module ``_asyncio`` as its ``__module__``.
    text = text.replace("_asyncio.", "asyncio.")
    for prefix in ("typing.", "collections.abc.", "shiori_sdk."):
        text = text.replace(prefix, "")
    return text.replace("NoneType", "None")


def _paragraph(text: str) -> str:
    return " ".join(text.split())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when docs/_handbook/plugin-api.md is stale",
    )
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = ""
        if args.output.is_file():
            current = args.output.read_text(encoding="utf-8")
        if current != text:
            print(
                "plugin-api.md is stale. Run python -m scripts.gen_plugin_api",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
